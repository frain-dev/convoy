"""Publish a stable release formula using separate author and reviewer apps."""

import base64
import json
import os
import re
import urllib.error
import urllib.request


TAP = "frain-dev/homebrew-tools"
SOURCE = "frain-dev/convoy"
AUTHOR = "convoy-homebrew-bot[bot]"


def api(path, token, method="GET", data=None):
    request = urllib.request.Request(
        "https://api.github.com/" + path,
        headers={"Authorization": "Bearer " + token,
                 "Accept": "application/vnd.github+json",
                 "X-GitHub-Api-Version": "2022-11-28"},
        method=method,
        data=None if data is None else json.dumps(data).encode(),
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def formula(tag, release):
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError("Only stable version tags are supported")
    if release["tag_name"] != tag or release["draft"] or release["prerelease"]:
        raise ValueError("Release must be published and stable")
    version = tag[1:]
    assets = {asset["name"]: asset for asset in release["assets"]}
    parts = [
        '# typed: false\n# frozen_string_literal: true\n\n',
        '# This file was generated by GoReleaser. DO NOT EDIT.\n',
        'class Convoy < Formula\n',
        '  desc "A fast & secure open source webhooks service"\n',
        '  homepage "https://getconvoy.io/"\n',
        f'  version "{version}"\n  license "MPL-2.0"\n',
    ]
    for operating_system, ruby_os in (("darwin", "macos"), ("linux", "linux")):
        parts.append(f"\n  on_{ruby_os} do\n")
        for architecture, ruby_cpu in (("amd64", "intel"), ("arm64", "arm")):
            name = f"convoy_{version}_{operating_system}_{architecture}.tar.gz"
            asset = assets[name]
            url = f"https://github.com/{SOURCE}/releases/download/{tag}/{name}"
            digest = asset.get("digest", "")
            if (asset["browser_download_url"] != url or asset["size"] <= 0
                    or asset["state"] != "uploaded"
                    or not re.fullmatch(r"sha256:[a-f0-9]{64}", digest)):
                raise ValueError("Invalid published release archive")
            cpu = f"Hardware::CPU.{ruby_cpu}?"
            if operating_system == "linux":
                cpu += " && Hardware::CPU.is_64_bit?"
            parts.extend([
                f"    if {cpu}\n",
                f'      url "{url}"\n      sha256 "{digest[7:]}"\n',
                ('\n' if operating_system == 'darwin' else '') + '      define_method(:install) do\n',
                '        bin.install "convoy"\n      end\n    end\n',
            ])
        parts.append("  end\n")
    return "".join(parts) + "end\n"


def content(ref, token):
    result = api(f"repos/{TAP}/contents/convoy.rb?ref={ref}", token)
    return base64.b64decode(result["content"]).decode(), result["sha"]


def validate_pr(pr, files, head, base):
    if (pr["state"] != "open" or pr["draft"]
            or pr["user"]["login"] != AUTHOR
            or pr["base"]["ref"] != "main"
            or pr["base"]["repo"]["full_name"] != TAP
            or pr["head"]["repo"]["full_name"] != TAP
            or pr["head"]["sha"] != head
            or pr["base"]["sha"] != base
            or pr["changed_files"] != 1 or len(files) != 1
            or files[0]["filename"] != "convoy.rb"
            or files[0]["status"] != "modified"):
        raise ValueError("PR is outside the formula automation allowlist")


def release_branch(branch, base, blob, expected, tag, token):
    """Resume only an empty base branch or this app's exact one-file commit."""
    head = base
    try:
        api(f"repos/{TAP}/git/refs", token, "POST",
            {"ref": "refs/heads/" + branch, "sha": base})
    except urllib.error.HTTPError as error:
        if error.code != 422:
            raise
        head = api(f"repos/{TAP}/git/ref/heads/{branch}", token)["object"]["sha"]
    if head != base:
        commit = api(f"repos/{TAP}/commits/{head}", token)
        if (not commit.get("author") or commit["author"]["login"] != AUTHOR
                or [parent["sha"] for parent in commit["parents"]] != [base]
                or len(commit["files"]) != 1
                or commit["files"][0]["filename"] != "convoy.rb"
                or commit["files"][0]["status"] != "modified"
                or content(head, token)[0] != expected):
            raise ValueError("Existing release branch is not this app's exact formula update")
        return head
    commit = api(f"repos/{TAP}/contents/convoy.rb", token, "PUT", {
        "message": f"chore: update convoy to {tag}", "branch": branch,
        "sha": blob, "content": base64.b64encode(expected.encode()).decode(),
    })
    return commit["commit"]["sha"]


def main():
    tag = os.environ["RELEASE_TAG"]
    # Validate before using the tag in any API path.
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError("Only stable version tags are supported")
    publisher = os.environ["HOMEBREW_PUBLISHER_TOKEN"]
    reviewer = os.environ["HOMEBREW_REVIEWER_TOKEN"]
    release = api(f"repos/{SOURCE}/releases/tags/{tag}", os.environ["GH_TOKEN"])
    expected = formula(tag, release)
    latest = api(f"repos/{SOURCE}/releases/latest", os.environ["GH_TOKEN"])
    if latest["id"] != release["id"]:
        raise ValueError("Refusing to publish an older release")
    base = api(f"repos/{TAP}/git/ref/heads/main", publisher)["object"]["sha"]
    old, blob = content(base, publisher)
    if old == expected:
        print(f"Homebrew formula already matches {tag}; no PR required.")
        return
    old_version = re.search(r'^  version "(\d+\.\d+\.\d+)"$', old, re.M)
    if old_version is None or tuple(map(int, old_version[1].split('.'))) >= tuple(map(int, tag[1:].split('.'))):
        raise ValueError("Refusing a formula downgrade or same-version rewrite")
    branch = f"convoy-{tag[1:]}"
    existing = api(f"repos/{TAP}/pulls?state=all&head=frain-dev:{branch}&per_page=100", publisher)
    if existing and (len(existing) != 1 or existing[0]["state"] != "open"
                     or existing[0]["user"]["login"] != AUTHOR):
        raise ValueError("Existing release PR requires human inspection")
    head = release_branch(branch, base, blob, expected, tag, publisher)
    pr = existing[0] if existing else api(f"repos/{TAP}/pulls", publisher, "POST", {
        "title": f"chore: update convoy to {tag}", "head": branch, "base": "main",
        "body": f"Update the formula to the published [{tag}](https://github.com/{SOURCE}/releases/tag/{tag}) archives and SHA256 checksums.",
    })
    number = pr["number"]
    print(pr["html_url"])
    pr_path = f"repos/{TAP}/pulls/{number}"
    pr = api(pr_path, reviewer)
    files = api(pr_path + "/files?per_page=100", reviewer)
    validate_pr(pr, files, head, base)
    actual, _ = content(head, reviewer)
    # Compare the complete file without evaluating any Ruby from the PR.
    if actual != expected:
        raise ValueError("Formula does not match independently validated release assets")
    if api(f"repos/{TAP}/git/ref/heads/main", reviewer)["object"]["sha"] != base:
        raise ValueError("Main advanced; leave this PR for human review")
    api(pr_path + "/reviews", reviewer, "POST", {
        "event": "APPROVE", "commit_id": head,
        "body": "Validated formula-only change against published stable release archives and SHA256 checksums.",
    })
    # Exact-head merge uses normal repository protections; no admin bypass.
    result = api(pr_path + "/merge", publisher, "PUT", {"sha": head, "merge_method": "squash"})
    if not result.get("merged"):
        raise RuntimeError("Approval succeeded but merge failed")
    merged_formula, _ = content(result["sha"], publisher)
    if merged_formula != expected:
        raise RuntimeError("Merged formula verification failed")
    print(f"Published Homebrew formula {tag} at {result['sha']}")


if __name__ == "__main__":
    main()
